#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════
   Fold the built app into one file.

   The repository has always carried a single-file build of
   SafeNexus at ../safenexus.html — one file you can open from a
   USB stick with no server and no toolchain. Now that the platform
   is thirteen modules rather than one, maintaining that by hand
   would mean maintaining the whole application twice, and the two
   copies would drift apart within a week.

   So it is generated instead: this inlines the CSS and JS emitted
   by `vite build` into the index shell and writes the result to
   ../safenexus.html. Same application, same data, one file.
   ══════════════════════════════════════════════════════════════ */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '..', 'dist-single');
const out = resolve(here, '..', '..', 'safenexus.html');

/* the IIFE build writes its two files flat; a default build nests
   them under assets/ — look in both rather than depend on either */
const find = (ext) => {
  for (const dir of [dist, join(dist, 'assets')]) {
    let names;
    try { names = readdirSync(dir); } catch { continue; }
    const hit = names.find((f) => f.endsWith(ext));
    if (hit) return join(dir, hit);
  }
  return null;
};

const jsPath = find('.js');
const cssPath = find('.css');
if (!jsPath) {
  console.error('Nothing to bundle. Run `npm run build:single`.');
  process.exit(1);
}

const html = readFileSync(join(dist, 'index.html'), 'utf8');
const cssText = cssPath ? readFileSync(cssPath, 'utf8') : '';
const jsText = readFileSync(jsPath, 'utf8');

/* An inline script cannot contain a raw </script>. Nothing in the
   source produces one, but escaping it costs nothing and removes the
   whole class of failure. */
const safe = (s) => s.replace(/<\/script>/gi, '<\\/script>');

const banner = `<!--
  SafeNexus ERP — single-file build.

  Generated from the React application in ./react by
  \`npm run build:single\`. Do not edit this file: edit the source and
  regenerate it, or the two copies drift apart.

  Built ${new Date().toISOString().slice(0, 10)}.
-->`;

/* Every insertion goes through a replacer FUNCTION, never a
   replacement string. A replacement string expands $&, $`, $' and $1
   — and minified JavaScript is full of `$` — which would splice the
   matched tag into the middle of the bundle. */
const put = (text) => () => text;

const single = html
  /* drop the emitted <link> and <script> tags, then inline their contents */
  .replace(/\s*<link[^>]+rel="stylesheet"[^>]*>/gi, '')
  .replace(/\s*<script[^>]*src="[^"]*"[^>]*><\/script>/gi, '')
  .replace('<!doctype html>', put(`<!doctype html>\n${banner}`))
  .replace('</head>', put(`  <style>\n${cssText}\n  </style>\n  </head>`))
  /* a classic script, not a module: a module will not load from a
     file:// URL, and this file exists to be opened straight off a disk */
  .replace('</body>', put(`  <script>\n${safe(jsText)}\n  </script>\n  </body>`));

writeFileSync(out, single);

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log(`safenexus.html  ${kb(single.length)}  (css ${kb(cssText.length)}, js ${kb(jsText.length)})`);
